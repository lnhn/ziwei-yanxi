/**
 * 十二宫详解 —— 每个宫一页，白话能看懂，专业层也站得住
 *
 * 为什么要有这一层：解盘时每宫只出一两句判语，够用不够懂。
 * 学盘的人真正卡住的地方是「这一宫到底管哪些事」「我这一格为什么这么读」
 * 「同样一颗星落到这一宫，说法为什么不一样」。这层就是补这三件事。
 *
 * 每宫的固定结构（页面按这个顺序渲染）：
 *   oneLine   一句话定调：先给人一个抓手
 *   scope     管什么：对应到生活里的具体事项，不是抽象的「主××」
 *   plain     白话读法：一段段讲明白，一般人读完能自己下判断
 *   pro       盘中怎么看：三方四正、对宫、宫干四化、大限流年——专业层
 *   signs     常见现象：可观察的迹象，用来对号，不是断语
 *   misread   常见误读：把最容易读错的地方挑明
 *   combos    主星组合：落到这一宫，几颗常客怎么读
 *   rel       与别的宫的关系：宫与宫是连动的，单看一格必误
 *   classic   经典出处：仅用本库收录的古籍原文，没有就如实说明
 *
 * 口径：三合派（三方四正、四化、宫位联动），不飞星。不写必成必败、不断生死婚期疾病。
 */

export interface PalaceScope {
  label: string;
  text: string;
}

export interface PalaceBlock {
  title: string;
  text: string;
}

export interface PalaceMisread {
  wrong: string;
  right: string;
}

export interface PalaceCombo {
  stars: string;
  note: string;
}

export interface PalaceKb {
  /** 宫名，带「宫」字 */
  name: string;
  slug: string;
  /** 顺序位，0 = 命宫，逆时针数 */
  idx: number;
  /** 古称 / 别称 */
  alias?: string;
  /** 一句话定调 */
  oneLine: string;
  /** 管什么 */
  scope: PalaceScope[];
  /** 白话读法，逐段 */
  plain: string[];
  /** 盘中怎么看（专业层） */
  pro: PalaceBlock[];
  /** 常见现象（可观察） */
  signs: string[];
  /** 常见误读 */
  misread: PalaceMisread[];
  /** 主星组合 */
  combos: PalaceCombo[];
  /** 与别的宫的关系 */
  rel: { name: string; slug: string; text: string }[];
  /** 经典出处（本库收录原文） */
  classic?: { text: string; source: string };
  /** 无原文时的说明 */
  classicNote?: string;
}

/** 十二宫顺序：命 → 兄弟 → 夫妻 → … → 父母（逆时针） */
export const PALACE_ORDER = [
  '命宫', '兄弟宫', '夫妻宫', '子女宫', '财帛宫', '疾厄宫',
  '迁移宫', '交友宫', '官禄宫', '田宅宫', '福德宫', '父母宫',
] as const;

/** 某一宫的三方四正：本宫 + 三合两宫 + 对宫（三合派取宫位的方式） */
export function sanFangOf(name: string): { own: string; trine: string[]; opposite: string } {
  const normalized = normalizePalaceName(name) ?? '';
  const i = PALACE_ORDER.indexOf(normalized as (typeof PALACE_ORDER)[number]);
  const at = (k: number) => PALACE_ORDER[((k % 12) + 12) % 12];
  if (i < 0) return { own: name, trine: [], opposite: '' };
  return { own: at(i), trine: [at(i + 4), at(i + 8)], opposite: at(i + 6) };
}

