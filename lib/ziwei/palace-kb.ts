/** 别名归一：iztro 用「仆役」，古籍用「奴仆」，现代多说「交友」 */
export const PALACE_ALIASES: Record<string, string> = {
  仆役: '交友宫', 奴仆: '交友宫', 交友: '交友宫',
  事业: '官禄宫', 官禄: '官禄宫',
  兄弟: '兄弟宫', 夫妻: '夫妻宫', 子女: '子女宫', 财帛: '财帛宫', 疾厄: '疾厄宫',
  迁移: '迁移宫', 田宅: '田宅宫', 福德: '福德宫', 父母: '父母宫', 命: '命宫', 命宫: '命宫',
};

/** 把盘上的宫名（可能不带「宫」、可能是别称）归一成十二宫标准名 */
export function normalizePalaceName(name: string): string | undefined {
  const raw = name.trim();
  if (PALACE_ALIASES[raw]) return PALACE_ALIASES[raw];
  const withGong = raw.endsWith('宫') ? raw : `${raw}宫`;
  if (PALACE_ALIASES[withGong]) return PALACE_ALIASES[withGong];
  return PALACE_ORDER.includes(withGong as (typeof PALACE_ORDER)[number]) ? withGong : undefined;
}

export function palaceSlugOf(name: string): string | undefined {
  const normalized = normalizePalaceName(name);
  if (!normalized) return undefined;
  return Object.values(PALACE_KB).find((p) => p.name === normalized)?.slug;
}
